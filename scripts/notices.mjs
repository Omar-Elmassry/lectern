// Writes THIRD_PARTY_NOTICES.md from an esbuild metafile: every npm package whose code
// ends up in a bundle, with its license text. Run by `node esbuild.mjs --production`.
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import path from 'path';

export function writeNotices(metafiles, out = 'THIRD_PARTY_NOTICES.md') {
  const dirs = new Set();
  for (const meta of metafiles) {
    for (const input of Object.keys(meta.inputs)) {
      const m = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input.replace(/\\/g, '/'));
      if (m) dirs.add(m[1]);
    }
  }
  const pkgs = [...dirs]
    .map((dir) => {
      const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
      const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
      const text = file ? readFileSync(path.join(dir, file), 'utf8').trim() : null;
      const license =
        (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type) ??
        (text && /\bMIT License\b/i.test(text) ? 'MIT' : 'see license text');
      const raw = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
      const repo = raw
        ?.replace(/^git\+/, '')
        .replace(/^git:\/\//, 'https://')
        .replace(/^github:/, 'https://github.com/')
        .replace(/^([\w-]+\/[\w.-]+)$/, 'https://github.com/$1')
        .replace(/\.git$/, '');
      return { name: pkg.name, version: pkg.version, license, text, repo };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  // The same package can be bundled from two places; list each name@version once.
  const seen = new Set();
  const unique = pkgs.filter((p) => !seen.has(`${p.name}@${p.version}`) && seen.add(`${p.name}@${p.version}`));

  const lines = [
    '# Third-party notices',
    '',
    'Lectern bundles the following open-source packages. Their license texts are reproduced',
    'below. This file is generated by `node esbuild.mjs --production`; do not edit it by hand.',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...unique.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    '',
  ];
  for (const p of unique) {
    lines.push(`## ${p.name} ${p.version}`, '');
    // A source link with every entry also covers licenses such as EPL-2.0 that ask
    // distributors to say where the source code can be obtained.
    if (p.repo) {
      lines.push(`Source code: ${p.repo}`, '');
    }
    if (p.text) {
      lines.push('```text', p.text.replace(/\r\n/g, '\n'), '```', '');
    } else {
      lines.push(`License: ${p.license}. The package ships no license file.`, '');
    }
  }
  writeFileSync(out, lines.join('\n'));
  return unique;
}
